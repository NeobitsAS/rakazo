// Fetches the models.dev logo of every model provider the catalog lists into public/providers,
// and writes the list of providers that have one. Run it after updating @earendil-works/pi-ai:
//
//   node apps/web/scripts/fetch-provider-logos.mjs
//
// A variant without a logo of its own (minimax-cn, azure-openai-responses) gets the logo of the
// name it builds on (minimax, azure). models.dev answers unknown names with a placeholder logo,
// so a logo that matches the placeholder counts as missing.
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";

const LOGO_URL = "https://models.dev/logos";
/** Catalog names that models.dev spells differently, or whose logo is the maker's. */
const LOGO_NAMES = {
  fireworks: "fireworks-ai",
  together: "togetherai",
  "kimi-coding": "moonshotai",
  "qwen-token-plan": "alibaba",
};
const repo = new URL("../../../", import.meta.url);
const publicDir = new URL("apps/web/public/providers/", repo);
const listFile = new URL("apps/web/src/lib/provider-logos.generated.ts", repo);
const catalog = new URL(
  "packages/adapters/node_modules/@earendil-works/pi-ai/dist/providers/all.js",
  repo,
);

async function fetchLogo(name) {
  const response = await fetch(`${LOGO_URL}/${name}.svg`);
  return response.ok ? response.text() : null;
}

/** The provider's own logo, or that of the shorter names it builds on. */
async function logoFor(id, placeholder) {
  const parts = id.split("-");
  for (let length = parts.length; length > 0; length -= 1) {
    const name = parts.slice(0, length).join("-");
    const logo = await fetchLogo(LOGO_NAMES[name] ?? name);
    if (logo && logo !== placeholder) return logo;
  }
  return null;
}

const { builtinModels } = await import(catalog.href);
const ids = builtinModels()
  .getProviders()
  .map((provider) => provider.id)
  .sort();
const placeholder = await fetchLogo("no-such-provider-placeholder");

await mkdir(publicDir, { recursive: true });
for (const file of await readdir(publicDir)) await rm(new URL(file, publicDir));

const found = [];
for (const id of ids) {
  const logo = await logoFor(id, placeholder);
  if (!logo) continue;
  await writeFile(new URL(`${id}.svg`, publicDir), logo);
  found.push(id);
}

await writeFile(
  listFile,
  `// Generated by apps/web/scripts/fetch-provider-logos.mjs. Do not edit by hand.

/** Model providers with a logo in public/providers, as \`<id>.svg\`. */
export const PROVIDER_LOGOS: ReadonlySet<string> = new Set([
${found.map((id) => `  "${id}",`).join("\n")}
]);
`,
);
console.log(`${found.length} of ${ids.length} providers have a logo.`);
console.log(`Missing: ${ids.filter((id) => !found.includes(id)).join(", ") || "none"}`);
